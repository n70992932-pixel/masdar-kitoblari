// ---- i18n Engine ----
const I18n = {
  currentLang: 'uz',

  init() {
    const saved = localStorage.getItem('masdar-lang');
    if (saved && TRANSLATIONS[saved]) {
      this.currentLang = saved;
    }
    this.apply();
  },

  setLang(lang) {
    if (!TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('masdar-lang', lang);
    this.apply();
  },

  t(key) {
    return TRANSLATIONS[this.currentLang]?.[key] || TRANSLATIONS['uz']?.[key] || key;
  },

  apply() {
    // Translate text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = this.t(key);
      if (translated) el.textContent = translated;
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translated = this.t(key);
      if (translated) el.placeholder = translated;
    });

    // Update lang toggle active states
    document.querySelectorAll('.lang-toggle-pill__btn').forEach(btn => {
      btn.classList.toggle('lang-toggle-pill__btn--active', btn.dataset.lang === this.currentLang);
    });

    // Update HTML lang attribute
    document.documentElement.lang = this.currentLang === 'uz' ? 'uz' : 'ru';
  },

  isUzbek() {
    return this.currentLang === 'uz';
  }
};
